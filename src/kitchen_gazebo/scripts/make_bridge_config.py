#!/usr/bin/env python3
"""Writes config/bridge.yaml, the Gazebo <-> ROS 2 topic bridge for the kitchen scenario.

    python3 src/kitchen_gazebo/scripts/make_bridge_config.py
"""
import pathlib

from make_gazebo_urdfs import CARRIED_OBJECTS, CONTROLLED_JOINTS

OUT = pathlib.Path(__file__).resolve().parents[1] / 'config' / 'bridge.yaml'


def entry(ros, gz, ros_type, gz_type, direction):
    return (f'- ros_topic_name: "{ros}"\n  gz_topic_name: "{gz}"\n'
            f'  ros_type_name: "{ros_type}"\n  gz_type_name: "{gz_type}"\n  direction: {direction}\n')


def main():
    parts = ['# Generated by scripts/make_bridge_config.py - do not edit.\n'
             '# Gazebo <-> ROS 2 topics for the kitchen scenario (world "kitchen", robot model "pr2").\n',
             entry('/clock', '/clock', 'rosgraph_msgs/msg/Clock', 'gz.msgs.Clock', 'GZ_TO_ROS'),
             entry('/joint_states', '/world/kitchen/model/pr2/joint_state', 'sensor_msgs/msg/JointState',
                   'gz.msgs.Model', 'GZ_TO_ROS'),
             entry('/odom', '/model/pr2/odometry', 'nav_msgs/msg/Odometry', 'gz.msgs.Odometry', 'GZ_TO_ROS'),
             entry('/tf', '/model/pr2/pose', 'tf2_msgs/msg/TFMessage', 'gz.msgs.Pose_V', 'GZ_TO_ROS'),
             entry('/scan', '/scan', 'sensor_msgs/msg/LaserScan', 'gz.msgs.LaserScan', 'GZ_TO_ROS'),
             entry('/cmd_vel', '/pr2/cmd_vel', 'geometry_msgs/msg/Twist', 'gz.msgs.Twist', 'ROS_TO_GZ'),
             '\n# Joint position commands (ROS std_msgs/Float64 -> Gazebo JointPositionController).\n']
    for joint in CONTROLLED_JOINTS:
        parts.append(entry(f'/pr2/{joint}/cmd_pos', f'/pr2/{joint}/cmd_pos', 'std_msgs/msg/Float64',
                           'gz.msgs.Double', 'ROS_TO_GZ'))
    parts.append('\n# Carrying: attach / detach an object to a hand (DetachableJoint), and its state.\n')
    for side in ('l', 'r'):
        for obj in CARRIED_OBJECTS:
            for action in ('attach', 'detach'):
                topic = f'/pr2/{side}_gripper/{action}/{obj}'
                parts.append(entry(topic, topic, 'std_msgs/msg/Empty', 'gz.msgs.Empty', 'ROS_TO_GZ'))
            topic = f'/pr2/{side}_gripper/state/{obj}'   # "attached" / "detached", sent when it changes
            parts.append(entry(topic, topic, 'std_msgs/msg/String', 'gz.msgs.StringMsg', 'GZ_TO_ROS'))
    parts.append('\n# Ground-truth object poses (to check results; perception uses the head camera).\n')
    for obj in CARRIED_OBJECTS:
        parts.append(entry(f'/objects/{obj}/pose', f'/model/{obj}/pose', 'tf2_msgs/msg/TFMessage',
                           'gz.msgs.Pose_V', 'GZ_TO_ROS'))
    OUT.write_text('\n'.join(parts))
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
