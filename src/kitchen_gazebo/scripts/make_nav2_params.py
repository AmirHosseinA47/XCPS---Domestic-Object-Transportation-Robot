#!/usr/bin/env python3
"""Writes config/nav2_params.yaml: Jazzy's default Nav2 parameters adapted to the PR2.

    python3 src/kitchen_gazebo/scripts/make_nav2_params.py
"""
import pathlib

import yaml

DEFAULTS = pathlib.Path('/opt/ros/jazzy/share/nav2_bringup/params/nav2_params.yaml')
OUT = pathlib.Path(__file__).resolve().parents[1] / 'config' / 'nav2_params.yaml'

BASE_FRAME = 'base_footprint'

# Planar outline of the PR2 with the lab's parked arms, measured from the robot's TF in Gazebo:
# link frames reach x -0.29..0.34 and y -0.67..0.67 (the elbows); plus 3-5 cm for link size.
FOOTPRINT = '[[0.37, 0.72], [0.37, -0.72], [-0.34, -0.72], [-0.34, 0.72]]'

# Indoor speeds well below the PR2's limits (about 1 m/s); the base is holonomic.
MAX_VELOCITY = [0.4, 0.3, 0.8]     # vx, vy, wz
MIN_VELOCITY = [-0.2, -0.3, -0.8]


class NoAliasDumper(yaml.SafeDumper):
    """Writes repeated objects out in full instead of as YAML aliases."""

    def ignore_aliases(self, data):
        return True


def set_everywhere(node, key, value):
    """Sets `key` in every mapping of the parameter tree that already has it."""
    if isinstance(node, dict):
        if key in node:
            node[key] = value
        for child in node.values():
            set_everywhere(child, key, value)


def main():
    p = yaml.safe_load(DEFAULTS.read_text())
    set_everywhere(p, 'use_sim_time', True)
    for key in ('robot_base_frame', 'base_frame_id', 'base_frame'):
        set_everywhere(p, key, BASE_FRAME)

    controller = p['controller_server']['ros__parameters']
    controller['min_y_velocity_threshold'] = 0.001  # the default (0.5) would discard sideways motion
    controller['general_goal_checker'].update(xy_goal_tolerance=0.08, yaw_goal_tolerance=0.1)
    # Standing poses are close to furniture, so the last metres are slow: count 0.2 m in 15 s
    # as progress (default 0.5 m in 10 s triggers recoveries during the final approach).
    controller['progress_checker'].update(required_movement_radius=0.2, movement_time_allowance=15.0)
    follow = controller['FollowPath']
    follow.update(motion_model='Omni', vx_max=MAX_VELOCITY[0], vx_min=MIN_VELOCITY[0],
                  vy_max=MAX_VELOCITY[1], wz_max=MAX_VELOCITY[2])
    if 'TwirlingCritic' not in follow['critics']:
        follow['critics'].append('TwirlingCritic')  # recommended for omnidirectional bases
    follow.setdefault('TwirlingCritic', {'enabled': True, 'twirling_cost_power': 1,
                                         'twirling_cost_weight': 10.0})

    global_costmap = p['global_costmap']['global_costmap']['ros__parameters']
    local_costmap = p['local_costmap']['local_costmap']['ros__parameters']
    for costmap in (global_costmap, local_costmap):
        costmap.pop('robot_radius', None)
        costmap['footprint'] = FOOTPRINT
        costmap['footprint_padding'] = 0.0
    # Local costmap: the 2D laser only, instead of the default 3D voxel layer.
    local_costmap['plugins'] = ['obstacle_layer', 'inflation_layer']
    local_costmap.pop('voxel_layer', None)
    local_costmap['obstacle_layer'] = dict(global_costmap['obstacle_layer'])
    local_costmap['width'] = local_costmap['height'] = 4
    # Inflation must reach the footprint's circumscribed radius (0.81 m with the parked arms)
    # for the controller's footprint collision check; a steep decay keeps the aisles usable.
    local_costmap['inflation_layer'].update(inflation_radius=0.85, cost_scaling_factor=6.0)
    global_costmap['inflation_layer'].update(inflation_radius=0.85, cost_scaling_factor=5.0)

    # Collision monitor: slow down only when a collision is under 0.5 s away (default 1.2 s),
    # otherwise the robot stalls 10 cm in front of the counter where it has to stand.
    p['collision_monitor']['ros__parameters']['FootprintApproach']['time_before_collision'] = 0.5

    smoother = p['velocity_smoother']['ros__parameters']
    smoother.update(max_velocity=MAX_VELOCITY, min_velocity=MIN_VELOCITY,
                    max_accel=[1.0, 1.0, 1.5], max_decel=[-1.0, -1.0, -1.5])

    header = ('# Generated by scripts/make_nav2_params.py from Jazzy\'s default '
              'nav2_bringup/params/nav2_params.yaml - do not edit\n')
    # ROS cannot read YAML aliases (&id001), which PyYAML emits for objects used twice.
    OUT.write_text(header + yaml.dump(p, Dumper=NoAliasDumper, sort_keys=False))
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
